export function languageToSlug(language: string): string {
  return language
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function slugToLanguage(slug: string): string | undefined {
  return LANGUAGES.find(
    (lang) => languageToSlug(lang) === slug
  );
}

